// Types for the signal module. Raw values stay inside src/signals/.
// Downstream code (state, integrations, mcp, timeline) must not import this file.

export type TraceSample = { ts: number; value: number; stable: boolean };
export type RateSample = { ts: number; value: number; stable: boolean; confidence: number };
export type TalkingSample = { ts: number; detected: boolean; stable: boolean };

export type MetricsEvent = {
  t: 'metrics';
  ts: number;
  upperTrace: TraceSample[];
  rate: RateSample[];
  talking: TalkingSample[];
};
export type ValidationEvent = { t: 'validation'; ts: number; code: number; hint: string };
export type ProcessingEvent = { t: 'processing'; ts: number; status: number };
export type ErrorEvent = { t: 'error'; ts: number; code: number; message: string; retryable: boolean };

export type SignalEvent = MetricsEvent | ValidationEvent | ProcessingEvent | ErrorEvent;

export type RecordingHeader = {
  t: 'header';
  version: 1;
  /** `synthetic` files are generated by a script and contain no real measurements. */
  origin: 'live' | 'synthetic';
  startedAt: string;
  sdkVersion: string | null;
  note?: string;
};

export type SignalListener = (event: SignalEvent) => void;

/** Live camera and sample recordings implement this, so the pipeline cannot tell them apart. */
export interface SignalSource {
  readonly kind: 'live' | 'replay';
  /** Shown in the UI whenever this source is active. */
  readonly label: string;
  start(): Promise<void>;
  stop(): Promise<void>;
  subscribe(listener: SignalListener): () => void;
}

