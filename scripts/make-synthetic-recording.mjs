// Generates recordings/synthetic-*.jsonl. These exist so tests and first-run replay work before
// real sessions are recorded. They are not measurements of anyone, and each header says so.
import { writeFileSync } from 'node:fs';

const START_US = 1_800_000_000_000_000;
const SECOND = 1_000_000;
const SAMPLES_PER_SECOND = 3;
const round = (n) => Math.round(n * 1000) / 1000;

// Small seeded generator, so regenerating gives identical files.
function rng(seed) {
  let s = seed;
  return () => {
    s = (s * 1664525 + 1013904223) % 4294967296;
    return s / 4294967296;
  };
}

const WARM_UP_SECONDS = 32;
const FRAME_RATE_LOW = 11;
const FACE_TOO_HIGH = 15;

/**
 * Shaped like a real session: the trace is unreliable for the first 30 s, the SDK keeps
 * reporting a low frame rate even at 25 fps, talking arrives in bursts, and when someone
 * leaves the metrics stop while the hints say "face too high" rather than "no face".
 * segments: [{ seconds, face, talking, irregular }]
 */
function generate(name, seed, segments) {
  const rand = rng(seed);
  const lines = [
    JSON.stringify({
      t: 'header',
      version: 1,
      origin: 'synthetic',
      startedAt: new Date(START_US / 1000).toISOString(),
      sdkVersion: null,
      note: 'Generated by scripts/make-synthetic-recording.mjs. Not a real session.',
    }),
    JSON.stringify({ t: 'processing', ts: START_US, status: 2 }),
    JSON.stringify({ t: 'processing', ts: START_US + 1000, status: 3 }),
  ];
  let second = 0;
  let phase = 0;
  let period = 4.6;
  let depth = 1;
  for (const seg of segments) {
    for (let i = 0; i < seg.seconds; i += 1) {
      second += 1;
      const ts = START_US + second * SECOND;
      lines.push(JSON.stringify({ t: 'validation', ts: ts - 500_000, code: seg.face ? FRAME_RATE_LOW : FACE_TOO_HIGH, hint: '' }));
      if (!seg.face) continue;
      const upperTrace = [];
      // Talking makes the trace unreliable, and the SDK marks it so.
      const stable = second > WARM_UP_SECONDS && !seg.talking;
      for (let k = 0; k < SAMPLES_PER_SECOND; k += 1) {
        const sampleTs = ts - SECOND + (k * SECOND) / SAMPLES_PER_SECOND;
        const before = phase;
        phase += (2 * Math.PI) / (period * SAMPLES_PER_SECOND);
        // New breath: an irregular stretch changes rate and depth a lot, a steady one barely.
        if (Math.floor(before / (2 * Math.PI)) !== Math.floor(phase / (2 * Math.PI))) {
          const swing = seg.irregular ? 0.45 : 0.03;
          period = 4.6 * (1 + (rand() - 0.5) * 2 * swing);
          depth = 1 + (rand() - 0.5) * 2 * swing;
        }
        upperTrace.push({ ts: sampleTs, value: round(depth * Math.sin(phase)), stable });
      }
      lines.push(
        JSON.stringify({
          t: 'metrics',
          ts,
          upperTrace,
          rate: [{ ts, value: round(60 / period), stable, confidence: stable ? 60 : 20 }],
          // Quiet work reads as talking now and then. Real sessions showed up to 11%.
          talking: [{ ts, detected: seg.talking ? second % 3 === 0 : second % 50 === 0, stable: true }],
        }),
      );
    }
  }
  const path = `recordings/synthetic-${name}.jsonl`;
  writeFileSync(path, `${lines.join('\n')}\n`);
  console.log(`Wrote ${lines.length} lines to ${path}`);
}

const min = (m) => m * 60;

// Baseline, then a long steady stretch that should reach focus.
generate('focus-block', 11, [
  { seconds: min(4), face: true, irregular: true },
  { seconds: min(13), face: true },
]);
// Reaches focus, then a conversation breaks it.
generate('talking-interruption', 22, [
  { seconds: min(4), face: true, irregular: true },
  { seconds: min(12), face: true },
  { seconds: min(3), face: true, talking: true },
  { seconds: min(1), face: true },
]);
// Reaches focus, then the person leaves and comes back.
generate('away', 33, [
  { seconds: min(4), face: true, irregular: true },
  { seconds: min(12), face: true },
  { seconds: min(3), face: false },
  { seconds: min(1), face: true },
]);
