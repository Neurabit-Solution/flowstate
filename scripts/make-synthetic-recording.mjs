// Generates recordings/synthetic-smoke.jsonl: 60 s of made-up metrics with a talking stretch
// and a no-face stretch. It exists so tests and first-run replay work before any real session
// has been recorded. It is not a measurement of anyone, and its header says so.
import { writeFileSync } from 'node:fs';

const START_US = 1_800_000_000_000_000;
const SECOND = 1_000_000;
const lines = [
  JSON.stringify({
    t: 'header',
    version: 1,
    origin: 'synthetic',
    startedAt: new Date(START_US / 1000).toISOString(),
    sdkVersion: null,
    note: 'Generated by scripts/make-synthetic-recording.mjs. Not a real session.',
  }),
  JSON.stringify({ t: 'processing', ts: START_US, status: 2 }),
  JSON.stringify({ t: 'processing', ts: START_US + 1000, status: 3 }),
  JSON.stringify({ t: 'validation', ts: START_US + 2000, code: 0, hint: '' }),
];

const round = (n) => Math.round(n * 10000) / 10000;

for (let s = 1; s <= 60; s += 1) {
  const windowEnd = START_US + s * SECOND;
  const faceGone = s > 45 && s <= 55;
  if (s === 46) lines.push(JSON.stringify({ t: 'validation', ts: windowEnd - 500_000, code: 1, hint: '' }));
  if (s === 56) lines.push(JSON.stringify({ t: 'validation', ts: windowEnd - 500_000, code: 0, hint: '' }));
  if (faceGone) continue;

  const upperTrace = [];
  for (let i = 0; i < 5; i += 1) {
    const ts = windowEnd - SECOND + (i * SECOND) / 5;
    // About 13 breaths a minute.
    const phase = ((ts - START_US) / SECOND) * ((2 * Math.PI * 13) / 60);
    upperTrace.push({ ts, value: round(Math.sin(phase)), stable: true });
  }
  const talkingNow = s > 25 && s <= 35;
  lines.push(
    JSON.stringify({
      t: 'metrics',
      ts: windowEnd,
      upperTrace,
      rate: [{ ts: windowEnd, value: 13, stable: true, confidence: 80 }],
      talking: [{ ts: windowEnd, detected: talkingNow, stable: true }],
    }),
  );
}

writeFileSync('recordings/synthetic-smoke.jsonl', `${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length} lines to recordings/synthetic-smoke.jsonl`);
